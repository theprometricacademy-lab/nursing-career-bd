                       when 2 then (select id from public.exams where exam_type = 'diploma_nursing' and year = 2023) end,
       q.q_en, q.q_bn, q.o_en, q.o_bn, q.ans, q.e_en, q.e_bn, q.diff, q.prem,
       case when q.exam_key is not null then 'Sample model set' else 'Nursing Career BD' end, q.yr
from seed_q q
join public.subjects s on s.slug = q.slug
left join public.topics t on t.subject_id = s.id and t.name_en = q.topic_en;

